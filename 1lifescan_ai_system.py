# ── Helper function: train + predict ──────────────────────
def train_model(model, X_tr, y_tr, X_te, model_name):
    """
    Train a model and return predictions on the test set.

    Parameters
    ----------
    model      : instantiated (but unfitted) sklearn estimator
    X_tr       : scaled training features
    y_tr       : training labels
    X_te       : scaled test features
    model_name : string label for printing

    Returns
    -------
    y_pred     : numpy array of predictions on X_te
    """
    print(f"\n  ▶  Training  {model_name} ...")
    model.fit(X_tr, y_tr)           # learn from training data
    y_pred = model.predict(X_te)    # generate predictions on test data
    print(f"     {model_name} — training complete.")
    return y_pred

