"""██████████████████████████████████████████████████████████
 SECTION 9 ── FEATURE SCALING
██████████████████████████████████████████████████████████

----------------------------------------------------------
WHY IS SCALING REQUIRED?
─────────────────────────
Features like Age range from 28–77 while
Cholesterol ranges from 0–600.
Algorithms that use distance (SVM, KNN, Logistic
Regression) will incorrectly give more WEIGHT to
features with larger numeric ranges.

StandardScaler transforms each feature so that:
  new_value = (original_value - mean) / std_deviation
After scaling: mean = 0,  std = 1 for each feature.

IMPORTANT RULE:
  - Fit  (learn mean/std) ONLY on TRAINING data.
  - Transform BOTH train and test with those same stats.
  - Never fit on test data — that leaks future information!
----------------------------------------------------------
"""

print("\n" + "=" * 60)
print("  FEATURE SCALING  (StandardScaler)")
print("=" * 60)

# ── Instantiate the scaler ────────────────────────────────
scaler = StandardScaler()

# ── Peek at one column BEFORE scaling ────────────────────
example_col = 'Age'
print(f"\n  Example — Column '{example_col}' BEFORE scaling:")
print(f"    Mean : {X_train[example_col].mean():.2f}")
print(f"    Std  : {X_train[example_col].std():.2f}")
print(f"    Min  : {X_train[example_col].min():.2f}")
print(f"    Max  : {X_train[example_col].max():.2f}")

# ── Fit on training data, transform both sets ─────────────
# fit_transform on train: learns the statistics AND applies them
X_train_scaled = scaler.fit_transform(X_train)

# transform on test: uses the SAME mean/std learned from train
X_test_scaled  = scaler.transform(X_test)

# Convert back to DataFrames so column names are preserved
X_train_scaled = pd.DataFrame(X_train_scaled, columns=X.columns)
X_test_scaled  = pd.DataFrame(X_test_scaled,  columns=X.columns)

# ── Peek at the same column AFTER scaling ─────────────────
print(f"\n  Example — Column '{example_col}' AFTER scaling:")
print(f"    Mean : {X_train_scaled[example_col].mean():.4f}  (≈ 0)")
print(f"    Std  : {X_train_scaled[example_col].std():.4f}   (≈ 1)")
print(f"    Min  : {X_train_scaled[example_col].min():.4f}")
print(f"    Max  : {X_train_scaled[example_col].max():.4f}")

