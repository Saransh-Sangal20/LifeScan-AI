"""██████████████████████████████████████████████████████████
 SECTION 6 ── FEATURE ENGINEERING  (LABEL ENCODING)
██████████████████████████████████████████████████████████

----------------------------------------------------------
WHY DO WE NEED ENCODING?
─────────────────────────
Machine Learning algorithms work with NUMBERS.
Columns like Sex = 'M'/'F' or ChestPainType = 'ATA'
are strings — the algorithm cannot compute distances,
gradients, or splits on raw text.

Label Encoding assigns a unique integer to each category:
  Sex : M → 1,  F → 0

NOTE: Label Encoding implies ORDER (0 < 1 < 2 ...).
For features with no natural order, One-Hot Encoding is
theoretically better.  However, tree-based models (Random
Forest) handle Label-Encoded categoricals well, and for
this project Label Encoding keeps the data compact.
----------------------------------------------------------
"""

print("\n" + "=" * 60)
print("  FEATURE ENGINEERING — LABEL ENCODING")
print("=" * 60)

# ── Step 6.1 : Identify categorical columns ───────────────
categorical_cols = df.select_dtypes(include=['object']).columns.tolist()
print(f"\n  Categorical columns to encode: {categorical_cols}")

# ── Step 6.2 : Create and store a LabelEncoder per column ─
# We store each encoder in a dictionary so that during
# prediction we can reverse-transform if needed.
label_encoders = {}   # key = column name, value = fitted LabelEncoder

for col in categorical_cols:
    print(f"\n  Encoding column : '{col}'")

    # Inspect unique values BEFORE encoding
    unique_before = df[col].unique()
    print(f"    Unique values (before) : {sorted(unique_before)}")

    # Create a fresh LabelEncoder for this column
    le = LabelEncoder()

    # fit_transform:
    #   fit  → learn the mapping  e.g. {'ATA':0, 'ASY':1, 'NAP':2, 'TA':3}
    #   transform → apply mapping to the column
    df[col] = le.fit_transform(df[col])

    # Inspect unique values AFTER encoding
    unique_after = df[col].unique()
    print(f"    Unique values (after)  : {sorted(unique_after)}")

    # Print the explicit mapping for transparency
    mapping = dict(zip(le.classes_, le.transform(le.classes_)))
    print(f"    Mapping applied        : {mapping}")

    # Store the encoder for future use (inference time)
    label_encoders[col] = le

print(f"\n  Encoders stored for columns: {list(label_encoders.keys())}")

# ── Step 6.3 : Verify the DataFrame after encoding ────────
print("\n  DataFrame head after encoding:")
print(df.head())
print(f"\n  All dtypes after encoding:\n{df.dtypes}")
