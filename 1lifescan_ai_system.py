"""██████████████████████████████████████████████████████████
 SECTION 15 ── CUSTOM PREDICTION FUNCTION
██████████████████████████████████████████████████████████

----------------------------------------------------------
This function is the INFERENCE LAYER of the system.
In a production environment (Flask API, Streamlit app,
MERN backend), you would call this function with patient
data received from the frontend and return the risk label.

Pipeline inside the function:
  1. Accept raw patient data as a dictionary.
  2. Convert to a single-row DataFrame (same column order
     as training data).
  3. Encode categorical values using saved encoders.
  4. Scale using the saved StandardScaler.
  5. Predict using the saved model.
  6. Return the label AND the probability for display.
----------------------------------------------------------
"""

print("\n" + "=" * 60)
print("  CUSTOM PREDICTION FUNCTION")
print("=" * 60)

def predict_heart_disease(patient_data: dict,
                           model,
                           scaler,
                           encoders: dict,
                           feature_order: list) -> dict:
    """
    Predict heart disease risk for a single patient.

    Parameters
    ----------
    patient_data  : dict — raw patient values (strings for
                    categorical features, numbers for numeric).
    model         : trained sklearn classifier.
    scaler        : fitted StandardScaler.
    encoders      : dict mapping column name → LabelEncoder.
    feature_order : list of feature names in the exact order
                    used during training.

    Returns
    -------
    dict with keys:
        'prediction'  : int  (0 or 1)
        'label'       : str  ('No Heart Disease' or 'Heart Disease')
        'probability' : float (confidence of the positive class)
        'risk_level'  : str  ('Low', 'Moderate', 'High')
    """

    # ── Step 1: Create a single-row DataFrame ─────────────
    # This ensures the input has named columns, making it
    # immune to column-order mistakes.
    input_df = pd.DataFrame([patient_data])

    # ── Step 2: Reorder columns to match training order ───
    # The model was trained with a specific column order.
    # If the order changes, feature X[3] during prediction
    # might correspond to feature X[2] during training.
    input_df = input_df[feature_order]

    # ── Step 3: Encode categorical columns ────────────────
    for col, le in encoders.items():
        if col in input_df.columns:
            raw_val     = input_df[col].values[0]
            encoded_val = le.transform([raw_val])[0]
            input_df[col] = encoded_val

    # ── Step 4: Apply StandardScaler ──────────────────────
    input_scaled = scaler.transform(input_df)

    # ── Step 5: Predict ───────────────────────────────────
    prediction  = model.predict(input_scaled)[0]

    # predict_proba returns [[prob_class0, prob_class1]]
    probability = model.predict_proba(input_scaled)[0][1]

    # ── Step 6: Interpret result ──────────────────────────
    label = "Heart Disease Detected" if prediction == 1 \
            else "No Heart Disease"

    if probability < 0.35:
        risk_level = "Low"
    elif probability < 0.65:
        risk_level = "Moderate"
    else:
        risk_level = "High"

    return {
        'prediction'  : int(prediction),
        'label'       : label,
        'probability' : round(float(probability), 4),
        'risk_level'  : risk_level
    }

